// HSK 레벨별 필수 단어 큐레이션 데이터.
// 각 항목: 간체 한자 / 병음(성조) / 한국어 뜻 / 품사 / (선택) 예문
// 데이터는 계속 확장 가능한 구조. 예문은 학습 효과가 큰 기초 단어 위주로 수록.

type Ex = { hanzi: string; pinyin: string; meaning: string }
type Raw = [hanzi: string, pinyin: string, meaning: string, pos: string, ex?: Ex]

function build(level: HskLevel, rows: Raw[]): Word[] {
  return rows.map(([hanzi, pinyin, meaning, pos, example], i) => ({
    id: `h${level}-${i + 1}`,
    hanzi,
    pinyin,
    meaning,
    pos,
    level,
    example,
  }))
}

